const normalize = s =>
  String(s || '')
    .toLowerCase()
    .replace(/\s+/g, '');

// 검색어 → 찾을 단어 목록 + 카테고리 · 태그 이름 일치
export function expandQuery(query, {categories = [], tags = []} = {}) {
  const q = normalize(query);
  if (!q) return null;
  const terms = new Set([q]);
  // 띄어쓰기를 지운 검색어 전체가 동의어 사전에 있거나, 2글자 이상 사전 단어를 포함하면 확장합니다. (예: '수제햄버거' → 햄버거)
  for (const [key, list] of Object.entries(SYNONYMS)) {
    if (q === key || (key.length >= 2 && q.includes(key))) for (const w of list) terms.add(normalize(w));
  }
  const match = name =>
    q.length >= 2 && (normalize(name).includes(q) || q.includes(normalize(name).replace(/&.*/, '')));
  return {
    q,
    terms: [...terms],
    categoryIds: categories.filter(c => c.name.length >= 2 && match(c.name)).map(c => c.id),
    tagIds: tags.filter(t => match(t.name)).map(t => t.id)
  };
}

// 화면에 보여줄 '함께 찾은 말' (검색어 자신 제외, 최대 6개)
export const extraTerms = ex => (ex ? ex.terms.filter(t => t !== ex.q).slice(0, 6) : []);

export function menuMatches(menu, ex) {
  const name = normalize(menu.name);
  if (ex.terms.some(t => name.includes(t))) return true;
  if ((menu.categoryIds || []).some(id => ex.categoryIds.includes(id))) return true;
  return (menu.tagIds || []).some(id => ex.tagIds.includes(id));
}
export const restaurantMatches = (r, ex) => {
  const name = normalize(r.name);
  return ex.terms.some(t => name.includes(t));
};
